/// Replacing your own password. The current one is required even though the
/// caller is already authenticated: a token left behind on an unlocked
/// machine should not be enough to lock the real owner out of the account.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ChangePasswordRequest {
    pub current_password: String,
    pub new_password: String,
}

/// Creating an account for somebody and putting them in the team, in one
/// step. The password is generated by the server, not supplied here - see
/// `password::generate_password` for why.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ProvisionMemberRequest {
    pub email: String,
    /// Shown in the member list. Optional: the local part of the email is a
    /// reasonable stand-in until they set their own.
    pub display_name: Option<String>,
    /// The role to give them immediately. Optional, but the reason this
    /// exists: an account created without one can do nothing until somebody
    /// remembers to come back and assign it.
    pub role_id: Option<Uuid>,
}

/// The one and only time the generated password is readable.
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProvisionedMember {
    pub user: UserProfile,
    /// Stored only as an Argon2 hash; this is the plaintext, returned once
    /// and never obtainable again.
    pub temporary_password: String,
    pub role_assigned: bool,
}

