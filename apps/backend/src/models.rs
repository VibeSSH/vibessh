use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Matches the explicit column list every query in auth.rs selects (never
/// `SELECT *`) - `updated_at` isn't included since nothing reads it yet; a
/// later stage that adds profile editing brings it back then.
#[derive(sqlx::FromRow)]
pub struct User {
    pub id: Uuid,
    pub email: String,
    pub password_hash: String,
    pub display_name: String,
    pub created_at: DateTime<Utc>,
    /// True for an account somebody else created - see
    /// `migrations/0008_provisioned_accounts.sql`. While it holds, the
    /// account may only read its own profile and set a new password.
    pub must_change_password: bool,
}

/// What a client is ever shown about a user - `password_hash` never leaves
/// this service, not even to its own authenticated owner.
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UserProfile {
    pub id: Uuid,
    pub email: String,
    pub display_name: String,
    pub created_at: DateTime<Utc>,
    /// Told to the client so it can send the user straight to the change
    /// screen. The backend refuses everything else regardless, so this is
    /// for the interface's benefit, never the enforcement.
    pub must_change_password: bool,
}

impl From<&User> for UserProfile {
    fn from(user: &User) -> Self {
        UserProfile {
            id: user.id,
            email: user.email.clone(),
            display_name: user.display_name.clone(),
            created_at: user.created_at,
            must_change_password: user.must_change_password,
        }
    }
}

